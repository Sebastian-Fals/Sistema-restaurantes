from contextlib import AbstractContextManager
from datetime import datetime
from typing import Protocol

from .domain import CardState, ProgramState, PurchaseState, RewardState


class LoyaltyRepository(Protocol):
    """Puerto de persistencia. Los métodos *_for_update/lock_* bloquean la fila hasta el fin de atomic()."""

    def atomic(self) -> AbstractContextManager: ...
    def lock_business(self, business_id: int) -> None: ...
    def program(self, business_id: int) -> ProgramState | None: ...
    def customer_id_by_email(self, email: str) -> int | None: ...
    def customer_id_by_card_code(self, business_id: int, code: str) -> int | None: ...
    def get_or_create_card(self, business_id: int, customer_id: int) -> CardState:
        """Idempotente y seguro ante creaciones concurrentes de la misma tarjeta."""
    def lock_card(self, business_id: int, customer_id: int) -> CardState: ...
    def save_stamps(self, card_id: int, stamps: int) -> None: ...
    def purchase_by_reference(self, business_id: int, reference: str) -> PurchaseState | None: ...
    def purchase_for_update(self, business_id: int, purchase_id: int) -> PurchaseState | None: ...
    def add_purchase(
        self, business_id: int, customer_id: int, amount_cop: int, reference: str, staff_id: int
    ) -> PurchaseState: ...
    def add_reward(
        self, business_id: int, customer_id: int, purchase_id: int, expires_at: datetime
    ) -> RewardState: ...
    def pending_stamp_count(self, business_id: int, customer_id: int) -> int: ...
    def contribution_count(self, reward_id: int) -> int: ...
    def release_reward_stamps(self, reward_id: int) -> None: ...
    def reward_for_update(self, business_id: int, reward_id: int) -> RewardState | None: ...
    def mark_redeemed(self, reward_id: int, staff_id: int, at: datetime) -> None: ...
    def mark_voided(self, reward_id: int) -> None: ...
    def add_reversal(self, purchase_id: int, reason: str, admin_id: int) -> None: ...
    def set_consent(self, business_id: int, customer_id: int, channel: str, granted: bool) -> None: ...
    def anonymize_customer(self, customer_id: int) -> None:
        """Desactiva la cuenta, quita el correo y borra consentimientos; conserva compras."""
